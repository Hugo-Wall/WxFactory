def _interpolate_squall_line_background(z):
    z0 = squall_line_background[:, 0]
    θ0 = squall_line_background[:, 1]
    qv0 = squall_line_background[:, 2]

    θ = torch.from_numpy(numpy.interp(z, z0, θ0))
    qv = torch.from_numpy(numpy.interp(z, z0, qv0))
    return θ, qv


def squall_line(geom, metric, param: Configuration):
    x1, x3 = geom.X1, geom.X3  # physical x and z, (ne3, ne2, ne1, ns**3)

    uu = torch.clamp(-12 + 0.0048 * x3, max=0.0)
    ww = torch.zeros_like(x1)
    θ, qv = _interpolate_squall_line_background(x3)
    qc = torch.zeros_like(x1)
    qr = torch.zeros_like(x1)

    xc, zc, pert = 75_000.0, 2000.0, 3.0
    rc, rx, rz = 1.0, 10_000.0, 1500.0
    θc = 3.0

    r = torch.sqrt((x1 - xc) ** 2 / rx**2 + (x3 - zc) ** 2 / rz**2)
    Δθ = torch.where(r <= rc, θc * torch.cos(0.5 * torch.pi * r), 0.0)
    θ += Δθ

    exner = 1.0 - gravity / (cpd * θ) * x3

    ρ = p0 / (Rd * θ) * exner ** (cvd / Rd)

    # TODO: don't do this here
    Q = torch.zeros((8,) + geom.grid_shape_3d_new, dtype=x1.dtype)
    Q[idx_rho] = ρ
    physical_momentum = torch.stack((ρ * uu, torch.zeros_like(ρ), ρ * ww))
    Q[1:4] = metric.volume.covariant_from_physical(physical_momentum / ρ)
    Q[idx_rho_theta] = ρ * θ
    Q[5] = ρ * qv
    Q[6] = ρ * qc
    Q[7] = ρ * qr

    return Q
